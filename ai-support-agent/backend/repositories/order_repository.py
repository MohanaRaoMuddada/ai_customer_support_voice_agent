"""
repositories/order_repository.py — Order Data Access Object
=============================================================

OrderRepository is the single source of truth for all SQL interactions
with the ``orders`` table. No SQL is written outside this class.

Why a class here:
    The repository pattern encapsulates the full data-access lifecycle for
    one domain entity (orders). Holding ``db_path`` as instance state avoids
    threading it through every function call. It also creates a clean seam
    for testing — swap the real repository with a mock without changing any
    service code (Dependency Inversion Principle).
"""

import sqlite3
from typing import Optional

from core.logger import get_logger
from database.connection import get_connection
from models.database_models import OrderRecord

logger = get_logger(__name__)


class OrderRepository:
    """
    Data access layer for the ``orders`` table.

    All SQL queries for order data live here — services never write SQL.

    Attributes:
        db_path (str): Absolute path to the SQLite database file.
    """

    def __init__(self, db_path: str) -> None:
        self.db_path = db_path

    # ------------------------------------------------------------------
    # Read operations
    # ------------------------------------------------------------------

    def get_by_id(self, order_id: int) -> Optional[OrderRecord]:
        """
        Retrieve a single order by its unique ID.

        Args:
            order_id (int): The primary key of the order to look up.

        Returns:
            OrderRecord | None: The order as a typed dict, or ``None`` if
                                no matching row exists.

        Raises:
            sqlite3.Error: If the SELECT query fails unexpectedly.
        """
        logger.info("Fetching order with ID: %d", order_id)
        connection = get_connection(self.db_path)

        try:
            cursor = connection.cursor()
            cursor.execute(
                "SELECT id, customer_name, status, expected_delivery "
                "FROM orders WHERE id = ?",
                (order_id,),
            )
            row = cursor.fetchone()

            if row is None:
                logger.warning("Order ID %d not found in the database.", order_id)
                return None

            order: OrderRecord = dict(row)  # type: ignore[assignment]
            logger.info("Order %d retrieved successfully.", order_id)
            return order

        except sqlite3.Error as exc:
            logger.error("Failed to fetch order %d: %s", order_id, exc)
            raise
        finally:
            connection.close()

    # ------------------------------------------------------------------
    # Write operations
    # ------------------------------------------------------------------

    def create(
        self,
        customer_name: str,
        status: str,
        expected_delivery: str,
    ) -> OrderRecord:
        """
        Insert a new order and return the newly created record.

        The ``id`` is auto-generated by SQLite's INTEGER PRIMARY KEY
        auto-increment mechanism.

        Args:
            customer_name     (str): Full name of the customer.
            status            (str): Initial order status (e.g., "Processing").
            expected_delivery (str): Expected delivery date string.

        Returns:
            OrderRecord: The complete order including its auto-assigned ID.

        Raises:
            sqlite3.Error: If the INSERT fails (e.g., constraint violation).
        """
        logger.info("Creating new order for customer: %s", customer_name)
        connection = get_connection(self.db_path)

        try:
            cursor = connection.cursor()
            cursor.execute(
                "INSERT INTO orders (customer_name, status, expected_delivery) "
                "VALUES (?, ?, ?)",
                (customer_name, status, expected_delivery),
            )
            new_id = cursor.lastrowid
            connection.commit()
            logger.info("New order created with ID: %d", new_id)

            return OrderRecord(
                id=new_id,
                customer_name=customer_name,
                status=status,
                expected_delivery=expected_delivery,
            )

        except sqlite3.Error as exc:
            logger.error("Failed to create order for %s: %s", customer_name, exc)
            connection.rollback()
            raise
        finally:
            connection.close()

    def update_status(self, order_id: int, status: str) -> Optional[OrderRecord]:
        """
        Update the ``status`` field of an existing order.

        Args:
            order_id (int): The ID of the order to update.
            status   (str): The new status value.

        Returns:
            OrderRecord | None: The updated order, or ``None`` if the order
                                does not exist.

        Raises:
            sqlite3.Error: If the UPDATE fails unexpectedly.
        """
        logger.info("Updating status of order %d to '%s'", order_id, status)
        connection = get_connection(self.db_path)

        try:
            cursor = connection.cursor()
            cursor.execute(
                "UPDATE orders SET status = ? WHERE id = ?",
                (status, order_id),
            )

            if cursor.rowcount == 0:
                logger.warning("Update failed: Order ID %d does not exist.", order_id)
                return None

            connection.commit()
            logger.info("Order %d status updated to '%s'.", order_id, status)

        except sqlite3.Error as exc:
            logger.error("Failed to update order %d: %s", order_id, exc)
            connection.rollback()
            raise
        finally:
            connection.close()

        # Fetch and return the updated record in a fresh connection
        return self.get_by_id(order_id)
